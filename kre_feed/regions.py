def sido_of(code: str | None) -> str:
    return SIDO_BY_PREFIX.get((code or "")[:2], "")


def region_label(region_key: str, with_sido: bool = False) -> str:
    """'41135|정자동' → '성남시 분당구 정자동' (with_sido: '경기 성남시 분당구 정자동')"""
    sgg, _, umd = (region_key or "").partition("|")
    parts = [sido_of(sgg) if with_sido else "", sgg_name(sgg), umd]
    return " ".join(x for x in parts if x).strip()
